const fs=require('node:fs');
const vm=require('node:vm');
const assert=require('node:assert/strict');
const context={window:{}};
vm.runInNewContext(fs.readFileSync(require('node:path').join(__dirname,'../js/policy.js'),'utf8'),context);
const p=context.window.SL_POLICY;
let count=0;
function check(v,desc){assert.ok(v,desc);count++}
check(p.validIPv4('192.0.2.20'), 'valid IPv4');
check(!p.validIPv4('192.0.2.256'), 'overflow octet');
check(!p.validIPv4('192.0.2.010'), 'leading zero');
check(p.validPeer('192.0.2.0/24'),'CIDR');
check(!p.validPeer('192.0.2.0/33'),'invalid CIDR');
check(!p.validPeer('192.0.2.20/garbage'),'invalid prefix');
check(p.validAccount('demo_reader'), 'account valid');
check(!p.validAccount('bad account'), 'account space');
check(p.validShare('Study'), 'share valid');
check(!p.validShare('..'), 'dot dot share rejected');
check(!p.validShare('CON'), 'reserved device share rejected');
check(!p.validShare('C$'), 'admin share blocked');
check(p.safePath('E:\\LANShare\\Study'),'safe path');
check(!p.safePath('C:\\Users'),'users protected');
check(!p.safePath('C:\\Windows\\System32'),'windows protected');
check(!p.safePath('C:\\'),'drive root blocked');
check(!p.safePath('E:\\LANShare\\..\\secret'),'dotdot blocked');
check(p.permissionSummary('read','change').startsWith('Read-only'),'SMB read limits NTFS change');
check(p.permissionSummary('change','read').startsWith('Read-only'),'NTFS read limits SMB change');
check(p.permissionSummary('change','change').startsWith('Modify'),'both modify');
console.log(`${count} policy tests passed.`);
